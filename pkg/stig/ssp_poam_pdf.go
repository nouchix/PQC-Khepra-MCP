// SSPExportData holds the data needed to render an SSP PDF.
// This avoids importing cmd-level types from pkg/stig.
type SSPExportData struct {
	SystemName           string
	SystemAbbreviation   string
	ResponsibleOrg       string
	SystemOwner          string
	ISSO                 string
	AuthorizingOfficial  string
	ImpactLevel          string
	CUICategories        []string
	SystemDescription    string
	SystemEnvironment    string
	BoundaryDescription  string
	ApplicableLaws       []string
	Version              string
	GeneratedAt          time.Time
	LastUpdatedAt        time.Time
	DAGChainDepth        int
	PQCSignature         string

	// Control stats
	TotalControls     int
	Implemented       int
	FailedScan        int
	Planned           int
	CompletionPercent float64

	// Control table: controlID → status
	Controls map[string]string
}

// ExportSSPToPDF produces a binary PDF for the SSP document at outputPath.
func ExportSSPToPDF(doc *SSPExportData, outputPath string) error {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(18, 18, 18)
	pdf.SetAutoPageBreak(true, 18)

	// ── Title Page ──────────────────────────────────────────────────────────
	pdf.AddPage()
	writeSSPTitlePage(pdf, doc)

	// ── Executive Summary ───────────────────────────────────────────────────
	pdf.AddPage()
	writeSSPSummary(pdf, doc)

	// ── Control Table ───────────────────────────────────────────────────────
	if len(doc.Controls) > 0 {
		pdf.AddPage()
		writeSSPControlTable(pdf, doc)
	}

	return pdf.OutputFileAndClose(outputPath)
}

