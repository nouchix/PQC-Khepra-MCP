func writeSSPControlTable(pdf *fpdf.Fpdf, doc *SSPExportData) {
	sectionHeader(pdf, "3. CONTROL IMPLEMENTATION TABLE")

	pdf.SetFont("Helvetica", "B", 9)
	pdf.SetFillColor(230, 230, 240)
	pdf.CellFormat(50, 7, "Control ID", "1", 0, "C", true, 0, "")
	pdf.CellFormat(0, 7, "Implementation Status", "1", 1, "C", true, 0, "")

	pdf.SetFont("Helvetica", "", 9)
	alt := false
	for id, status := range doc.Controls {
		if alt {
			pdf.SetFillColor(248, 248, 252)
		} else {
			pdf.SetFillColor(255, 255, 255)
		}
		alt = !alt

		// Color-code status
		switch status {
		case "IMPLEMENTED":
			pdf.SetTextColor(0, 120, 0)
		case "FAILED_SCAN":
			pdf.SetTextColor(180, 0, 0)
		case "PLANNED":
			pdf.SetTextColor(150, 100, 0)
		default:
			pdf.SetTextColor(80, 80, 80)
		}

		pdf.CellFormat(50, 6, id, "1", 0, "L", true, 0, "")
		pdf.CellFormat(0, 6, status, "1", 1, "L", true, 0, "")
		pdf.SetTextColor(0, 0, 0)
	}
}

